HEADER = "// GENERATED by tools/gen_rti_sources.py - do not edit by hand.\n"


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def remove_balanced(text: str, keyword: str) -> str:
    """Remove `keyword (...)` blocks with balanced parentheses."""
    out, i = [], 0
    while True:
        j = text.find(keyword, i)
        if j < 0:
            out.append(text[i:])
            return "".join(out)
        out.append(text[i:j])
        k = text.index("(", j)
        depth = 0
        while True:
            if text[k] == "(":
                depth += 1
            elif text[k] == ")":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        i = k + 1


def split_top_level(params: str):
    parts, depth, cur = [], 0, []
    for ch in params:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur))
    return [p.strip() for p in parts]


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def gen_exceptions():
    text = strip_comments((INC / "Exception.h").read_text())
    names = re.findall(r"^\s*RTI_EXCEPTION\(\s*(\w+)\s*\)", text, flags=re.M)
    lines = [HEADER, "#include <RTI/Exception.h>\n\nnamespace rti1516e\n{\n"]
    for n in names:
        lines.append(
            f"{n}::{n}(std::wstring const & message) RTI_NOEXCEPT : _msg(message) {{}}\n"
            f"std::wstring {n}::what() const RTI_NOEXCEPT {{ return L\"{n}: \" + _msg; }}\n"
        )
    lines.append("}\n")
    (OUT / "Exceptions.cpp").write_text("".join(lines))
    return len(names)


def parse_ambassador():
    text = strip_comments((INC / "RTIambassador.h").read_text())
    body = text[text.index("class RTI_EXPORT RTIambassador"):]
    body = remove_balanced(body, "RTI_THROW")
    methods = []
    for chunk in body.split(";"):
        c = norm(chunk)
        c = re.sub(r"^.*?\b(public|protected|private)\s*:\s*", "", c)
        if not c.startswith("virtual") or not re.search(r"=\s*0$", c):
            continue
        c = re.sub(r"=\s*0$", "", c[len("virtual"):]).strip()
        if c.startswith("~"):
            continue
        p0 = c.index("(")
        depth, p1 = 0, p0
        while True:
            if c[p1] == "(":
                depth += 1
            elif c[p1] == ")":
                depth -= 1
                if depth == 0:
                    break
            p1 += 1
        head, params, tail = c[:p0].strip(), c[p0 + 1:p1], c[p1 + 1:].strip()
        m = re.match(r"(.*?)(\w+)$", head)
        ret, name = m.group(1).strip(), m.group(2)
        plist = [re.sub(r"\s*=.*$", "", p) for p in split_top_level(params)]
        methods.append((ret, name, plist, tail))
    return methods


def gen_ambassador():
    methods = parse_ambassador()
    decl = [HEADER]
    stubs = [HEADER, '#include "../MqttRTIambassador.h"\n\nnamespace hla_mqtt\n{\n'
             "using namespace rti1516e;\n\n"]
    for ret, name, plist, tail in methods:
        params = ", ".join(plist)
        qual = (" " + tail) if tail else ""
        decl.append(f"{ret} {name}({params}){qual} override;\n")
        if name in IMPLEMENTED:
            continue
        stubs.append(
            f"{ret} MqttRTIambassador::{name}({params}){qual}\n"
            f"{{\n   notImplemented(L\"{name}\");\n}}\n\n"
        )
    stubs.append("}\n")
    (OUT / "RTIambassadorOverrides.inc").write_text("".join(decl))
    (OUT / "RTIambassadorStubs.cpp").write_text("".join(stubs))
    return len(methods)


